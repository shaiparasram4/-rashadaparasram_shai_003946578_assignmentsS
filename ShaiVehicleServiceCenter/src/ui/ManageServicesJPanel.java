    private void btnAddServiceActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddServiceActionPerformed
         if (txtServiceId.getText().trim().isEmpty()
            || txtServiceType.getText().trim().isEmpty()
            || txtCost.getText().trim().isEmpty()
            || txtMechanicName.getText().trim().isEmpty()
            || txtServiceDuration.getText().trim().isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "All service fields are required.",
                "Missing Information",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );

        return;
    }

    try {

        int serviceId =
                Integer.parseInt(txtServiceId.getText().trim());

        String serviceType =
                txtServiceType.getText().trim();

        double cost =
                Double.parseDouble(txtCost.getText().trim());

        String mechanicName =
                txtMechanicName.getText().trim();

        short serviceDuration =
                Short.parseShort(txtServiceDuration.getText().trim());

        if (serviceCatalog.searchServiceById(serviceId) != null) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "A service with this Service ID already exists.",
                    "Duplicate Service ID",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );

            return;
        }

        if (serviceId <= 0) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Service ID must be greater than 0.",
                    "Invalid Service ID",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );

            return;
        }

        if (cost < 0) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Cost cannot be negative.",
                    "Invalid Cost",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );

            return;
        }

        if (serviceDuration <= 0) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Service duration must be greater than 0.",
                    "Invalid Duration",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );

            return;
        }

        Service newService = new Service(
                serviceId,
                serviceType,
                cost,
                mechanicName,
                serviceDuration
        );

        serviceCatalog.addService(newService);

        populateTable();

        txtServiceId.setText("");
        txtServiceType.setText("");
        txtCost.setText("");
        txtMechanicName.setText("");
        txtServiceDuration.setText("");

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Service added successfully."
        );

    } catch (NumberFormatException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Service ID, Cost, and Service Duration must contain valid numbers.",
                "Invalid Input",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
      }
       
    }//GEN-LAST:event_btnAddServiceActionPerformed

