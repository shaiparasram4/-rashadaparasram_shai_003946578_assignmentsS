    private void populateTable() {

    DefaultTableModel model =
            (DefaultTableModel) tblServices.getModel();

    model.setRowCount(0);

    for (Service service : serviceCatalog.getServiceList()) {

        Object[] row = new Object[5];

        row[0] = service.getServiceId();
        row[1] = service.getServiceType();
        row[2] = service.getCost();
        row[3] = service.getMechanicName();
        row[4] = service.getServiceDuration();

        model.addRow(row);
    }
}

private void loadSelectedService() {

    int selectedRow = tblServices.getSelectedRow();

    if (selectedRow < 0) {
        return;
    }

    txtServiceId.setText(
            tblServices.getValueAt(selectedRow, 0).toString()
    );

    txtServiceType.setText(
            tblServices.getValueAt(selectedRow, 1).toString()
    );

    txtCost.setText(
            tblServices.getValueAt(selectedRow, 2).toString()
    );

    txtMechanicName.setText(
            tblServices.getValueAt(selectedRow, 3).toString()
    );

    txtServiceDuration.setText(
            tblServices.getValueAt(selectedRow, 4).toString()
    );
}
 



